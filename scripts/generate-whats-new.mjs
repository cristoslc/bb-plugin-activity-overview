#!/usr/bin/env node
/**
 * Derives lib/whats-new.generated.ts from CHANGELOG.md's published sections,
 * so the What's-new feed is never written twice. Each `## [version] -
 * <date>` H2 yields one entry; each column-0 bullet yields one item — the
 * bullet's bold lead sentence (lib/changelog-markdown.ts, leadFromBullet),
 * never the full prose — and each bullet's indented sub-bullets condensed
 * the same way as the item's children. Wired into the "test" and "build"
 * scripts, so every test run and every build embeds the current record.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parsePublishedChangelog, leadFromBullet } from "../lib/changelog-markdown.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const markdown = readFileSync(`${root}/CHANGELOG.md`, "utf8");
const entries = parsePublishedChangelog(markdown)
  .map((section) => ({
    version: section.version,
    items: section.subsections
      .flatMap((sub) => sub.bullets.map((bullet) => ({
        lead: leadFromBullet(bullet.text),
        children: bullet.children.map(leadFromBullet).filter(Boolean),
      })))
      .filter((item) => item.lead.length > 0),
  }))
  .filter((entry) => entry.items.length > 0);

const source = `/** Generated by scripts/generate-whats-new.mjs from CHANGELOG.md — do not edit. */
export const DERIVED_WHATS_NEW: readonly { version: string; items: readonly { lead: string; children: readonly string[] }[] }[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(`${root}/lib/whats-new.generated.ts`, source);